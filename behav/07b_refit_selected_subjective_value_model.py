#!/usr/bin/env python3
"""
07b_refit_selected_subjective_value_model.py
============================================

Optional final full-data refit AFTER the block-CV model has been inspected and
a model has been explicitly selected.

This fit is for reporting participant/group parameters. It is NOT the source of
the EEG target. EEG must use the corresponding out-of-fold file generated by
07a.
"""

from __future__ import annotations

import argparse
import json

import arviz as az
import numpy as np
import pandas as pd
import pymc as pm

from subjective_value_v4_common import (
    FULL_FIT_ROOT,
    MODEL_DEFINITIONS,
    OUTPUT_ROOT,
    build_model,
    load_all_behavior,
    participant_parameter_means,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--model",
        required=True,
        choices=list(
            MODEL_DEFINITIONS
        ),
    )

    parser.add_argument(
        "--draws",
        type=int,
        default=2000,
    )

    parser.add_argument(
        "--tune",
        type=int,
        default=2000,
    )

    parser.add_argument(
        "--chains",
        type=int,
        default=4,
    )

    parser.add_argument(
        "--cores",
        type=int,
        default=4,
    )

    parser.add_argument(
        "--target-accept",
        type=float,
        default=0.99,
    )

    parser.add_argument(
        "--random-seed",
        type=int,
        default=20261031,
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    FULL_FIT_ROOT.mkdir(
        parents=True,
        exist_ok=True,
    )

    data, participants = load_all_behavior()

    print(
        "=" * 84
    )
    print(
        "FINAL FULL-DATA SUBJECTIVE-VALUE REFIT"
    )
    print(
        f"Model: {args.model}"
    )
    print(
        f"Formula: {MODEL_DEFINITIONS[args.model]['formula']}"
    )
    print(
        f"Participants: {len(participants)}"
    )
    print(
        f"Trials: {len(data)}"
    )
    print(
        "=" * 84
    )

    model = build_model(
        data=
            data,
        model_name=
            args.model,
        participant_names=
            participants,
    )

    with model:
        idata = pm.sample(
            draws=
                args.draws,
            tune=
                args.tune,
            chains=
                args.chains,
            cores=
                min(
                    args.cores,
                    args.chains,
                ),
            target_accept=
                args.target_accept,
            random_seed=
                args.random_seed,
            return_inferencedata=
                True,
            progressbar=
                True,
        )

    idata.to_netcdf(
        FULL_FIT_ROOT
        / f"{args.model}.nc"
    )

    parameter_names = [
        "intercept",
        "money_slope",
        "pain_slope",
    ]

    if MODEL_DEFINITIONS[
        args.model
    ][
        "interactive"
    ]:
        parameter_names.append(
            "interaction_slope"
        )

    if MODEL_DEFINITIONS[
        args.model
    ][
        "nonlinear_pain"
    ]:
        parameter_names.append(
            "pain_exponent"
        )

    summary = az.summary(
        idata,
        var_names=
            parameter_names,
    )

    summary.to_csv(
        FULL_FIT_ROOT
        / f"{args.model}_summary.csv"
    )

    participant_table = participant_parameter_means(
        idata=
            idata,
        model_name=
            args.model,
        heldout_block=
            -1,
    )

    participant_table = participant_table.drop(
        columns=[
            "heldout_block",
        ]
    )

    participant_table.to_csv(
        FULL_FIT_ROOT
        / f"{args.model}_participant_parameters.csv",
        index=False,
    )

    n_divergences = int(
        idata.sample_stats[
            "diverging"
        ]
        .sum()
        .values
    )

    max_rhat = float(
        np.nanmax(
            summary[
                "r_hat"
            ]
            .replace(
                [
                    np.inf,
                    -np.inf,
                ],
                np.nan,
            )
        )
    )

    min_bulk_ess = float(
        np.nanmin(
            summary[
                "ess_bulk"
            ]
        )
    )

    diagnostics = {
        "model":
            args.model,
        "max_rhat":
            max_rhat,
        "min_bulk_ess":
            min_bulk_ess,
        "n_divergences":
            n_divergences,
        "IMPORTANT":
            (
                "Use block-CV OOF subjective values, not this full-data fit, "
                "as EEG targets."
            ),
    }

    (
        FULL_FIT_ROOT
        / f"{args.model}_diagnostics.json"
    ).write_text(
        json.dumps(
            diagnostics,
            indent=2,
        )
    )

    print(
        "\nFINAL FIT DIAGNOSTICS"
    )
    print(
        json.dumps(
            diagnostics,
            indent=2,
        )
    )
    print(
        f"\nOutputs: {FULL_FIT_ROOT}"
    )


if __name__ == "__main__":
    main()
